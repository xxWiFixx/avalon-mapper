// Разбор строки «Закроется через …» из тултипа портала.
// Главный случай здесь прислал игрок: приложение показало 24 ч 24 м там, где портал
// закрывался через 2 ч 24 м. Лишняя цифра приклеилась к часам слева — из значка
// песочных часов и хвоста надписи, — а верхней границы у часов не было вовсе.
const { parseDur, allDurations, sameNumber, MAX_HOURS } = require('../lib/recognize')._internal;

let ok = 0, fail = 0;
function t(name, fn) {
  try { fn(); console.log('  ОК     ', name); ok++; }
  catch (e) { console.log('  ПРОВАЛ ', name, '\n           ', e.message); fail++; }
}
function eq(a, b, what) { if (a !== b) throw new Error(`${what}: получил ${JSON.stringify(a)}, ждал ${JSON.stringify(b)}`); }
const hm = text => { const d = parseDur(text); return d ? Math.floor(d.sec / 3600) + ':' + String(Math.round(d.sec % 3600 / 60)).padStart(2, '0') : 'отвергнуто'; };

console.log('\n=== нормальные прочтения ===');

t('часы и минуты', () => {
  eq(hm('Закроется через 2 ч 24 м'), '2:24', 'кадр игрока');
  eq(hm('Закроется через 5 ч 36 м'), '5:36', 'обычный');
  eq(hm('19 ч 53 м'), '19:53', 'самый долгий портал в корпусе');
  // Живой кадр игрока: порталы за 21 час СУЩЕСТВУЮТ. Прежний потолок в 21 час отвергал
  // это верное число, и запасной разбор подхватывал таймер «Можно использовать» —
  // в карту уезжало «5 с» вместо 22 часов.
  eq(hm('Закроется через 22 ч 43 м'), '22:43', 'настоящее время с кадра игрока');
});

t('только минуты и только часы', () => {
  eq(hm('44 м'), '0:44', 'минуты');
  eq(hm('через 7 ч'), '7:00', 'часы');
});

t('минуты и секунды у скорого закрытия', () => {
  eq(hm('через 7 м 20 с'), '0:07', '7 минут 20 секунд');
});

console.log('\n=== то, чего не бывает, — отвергаем целиком ===');

t('ТОТ САМЫЙ СЛУЧАЙ: 24 ч 24 м вместо 2 ч 24 м', () => {
  eq(hm('Закроется через 24 ч 24 м'), 'отвергнуто', 'лишняя цифра в часах');
  eq(allDurations('Закроется через 24 ч 24 м').length, 0, 'и в списке вариантов пусто');
});

t('не проваливаемся на правило поменьше', () => {
  // «24 ч 24 м» не должно превратиться в «24 минуты»: одно неверное число вместо другого
  const d = parseDur('Закроется через 24 ч 24 м');
  eq(d, null, 'разбор');
});

t('граница ровно по MAX_HOURS', () => {
  eq(hm(`${MAX_HOURS} ч 00 м`), MAX_HOURS + ':00', 'на границе — принимаем');
  eq(hm(`${MAX_HOURS + 1} ч 10 м`), 'отвергнуто', 'за границей — нет');
});

t('часы без минут тоже ограничены', () => {
  eq(hm('через 30 ч'), 'отвергнуто', '30 часов у портала не бывает');
});

console.log('\n=== известные подмены букв OCR ===');

t('«ч» прочиталась как «4»', () => {
  eq(hm('2424 м'), '2:24', 'склеенное 2ч24м');
});

t('«О» вместо нуля', () => {
  eq(hm('1O м'), '0:10', 'десять минут');
});

console.log('\n=== одно число, прочитанное дважды ===');

// НАСТОЯЩАЯ причина ошибок в часах, найденная разбором и воспроизведённая на кадре:
// шрифт Albion рисует «ч» почти как «4», и tesseract читает ОДИН глиф дважды —
// сперва цифрой, потом буквой. «1 ч 59 м» → «14ч59м». Предел MAX_HOURS это не ловил:
// 14 меньше 21, поэтому страдали только ОДНОЧАСОВЫЕ порталы — ровно жалоба игрока.
const H = (h, m) => h * 3600 + m * 60;

t('удвоенная «ч»: верно младшее прочтение', () => {
  eq(sameNumber(H(1, 59), H(14, 59)), 'lo', '1ч59 против 14ч59');
  eq(sameNumber(H(1, 30), H(14, 30)), 'lo', 'случай игрока');
  eq(sameNumber(H(2, 20), H(24, 20)), 'lo', 'прежний случай 2ч24 → 24ч24 — тот же дефект');
  eq(sameNumber(H(2, 20), H(29, 20)), 'lo', 'иногда вместо «4» выходит «9»');
});

t('настоящие двузначные часы не трогаем', () => {
  eq(sameNumber(H(10, 2), H(19, 53)), null, 'разные числа');
  eq(sameNumber(H(1, 30), H(14, 31)), null, 'минуты разошлись — это не одно число');
  eq(sameNumber(H(1, 30), H(15, 30)), null, '15 не равно 1×10+4 и не 1×10+9');
  eq(sameNumber(H(0, 30), H(4, 30)), null, 'нулевые часы правилу не подходят');
});

t('потерянная единица по-прежнему работает — верно СТАРШЕЕ', () => {
  eq(sameNumber(H(7, 44), H(17, 44)), 'hi', 'часы 7 → 17');
  eq(sameNumber(H(1, 5), H(1, 15)), 'hi', 'минуты 5 → 15');
});

t('порядок аргументов не путается', () => {
  eq(sameNumber(H(14, 59), H(1, 59)), null, 'старшее первым — не наше дело');
  eq(sameNumber(H(3, 0), H(3, 0)), null, 'равные числа сливать нечего');
});

console.log(`\n${fail ? 'ЕСТЬ ПРОВАЛЫ' : 'ВСЁ ЗЕЛЕНО'}: ${ok}/${ok + fail} проверок пройдено`);
process.exit(fail ? 1 : 0);
