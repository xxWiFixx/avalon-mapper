// Разбор строки «имя зоны + время до закрытия». Проверяем ровно то, из-за чего
// правило и выбиралось: голые цифры не должны втихую менять смысл.
require('../ui/search-line.js');
const { parse, fmtDur, fmtAt } = globalThis.SEARCH_LINE;

let ok = 0, fail = 0;
function t(name, fn) {
  try { fn(); console.log('  ОК     ', name); ok++; }
  catch (e) { console.log('  ПРОВАЛ ', name, '\n           ', e.message); fail++; }
}
function eq(a, b, what) { if (a !== b) throw new Error(`${what}: получил ${JSON.stringify(a)}, ждал ${JSON.stringify(b)}`); }
// строка → часы и минуты одним куском, чтобы проверки читались как ожидание игрока
function hm(text) {
  const r = parse(text);
  if (r.error) return 'ошибка';
  if (r.sec == null) return 'нет времени';
  return Math.floor(r.sec / 3600) + ':' + String(Math.round((r.sec % 3600) / 60)).padStart(2, '0');
}

console.log('\n=== одно число — минуты, два — часы и минуты ===');

t('только имя — времени нет', () => {
  eq(parse('couexa').query, 'couexa', 'запрос');
  eq(hm('couexa'), 'нет времени', 'время');
});

t('одно число — минуты', () => {
  eq(hm('couexa 45'), '0:45', '45');
  eq(hm('couexa 7'), '0:07', '7');
  eq(hm('couexa 90'), '1:30', '90 минут — это полтора часа');
});

t('два числа — часы и минуты', () => {
  eq(hm('couexa 5 36'), '5:36', 'пробел');
  eq(hm('couexa 11 5'), '11:05', 'минуты без ведущего нуля — тот самый случай');
  eq(hm('couexa 0 7'), '0:07', 'ноль часов');
});

t('разделитель точка, двоеточие и «ч» — то же самое', () => {
  for (const s of ['couexa 5.36', 'couexa 5:36', 'couexa 5ч36', 'couexa 5ч36м', 'couexa 5 36']) {
    eq(hm(s), '5:36', s);
  }
});

t('115 — это 115 минут, а не час пятнадцать', () => {
  eq(hm('couexa 115'), '1:55', 'голые цифры всегда минуты');
  eq(hm('couexa 1.15'), '1:15', 'а час пятнадцать — с разделителем');
  eq(hm('couexa 1 15'), '1:15', 'или через пробел');
});

t('суффиксы «ч» и «м» поодиночке', () => {
  eq(hm('couexa 5ч'), '5:00', 'только часы');
  eq(hm('couexa 45м'), '0:45', 'только минуты');
  eq(hm('couexa 5h'), '5:00', 'латиница');
});

console.log('\n=== имя вырезается из строки правильно ===');

t('имя из двух слов и время', () => {
  const r = parse('fort sterling 5 36');
  eq(r.query, 'fort sterling', 'запрос');
  eq(r.sec, 5 * 3600 + 36 * 60, 'время');
});

t('имя с дефисом не ломается', () => {
  eq(parse('qiient-qi 1.15').query, 'qiient-qi', 'запрос');
  eq(hm('qiient-qi 1.15'), '1:15', 'время');
});

t('пустая строка и пробелы', () => {
  eq(parse('').query, '', 'пусто');
  eq(parse('   ').sec, null, 'только пробелы');
});

console.log('\n=== что должно быть ошибкой, а не молчаливой догадкой ===');

t('минут больше 59 при указанных часах', () => {
  eq(hm('couexa 5 70'), 'ошибка', '5 70');
  eq(hm('couexa 5.70'), 'ошибка', '5.70');
});

t('часов больше 48 не бывает', () => {
  eq(hm('couexa 99 30'), 'ошибка', '99 30');
  eq(hm('couexa 60ч'), 'ошибка', '60ч');
});

t('три числа подряд — не «имя и время»', () => {
  eq(hm('couexa 5 36 20'), 'ошибка', 'три числа');
  const r = parse('couexa 5 36 20');
  eq(r.query, 'couexa', 'запрос всё равно вырезан');
});

t('ноль — не время', () => {
  eq(parse('couexa 0').sec, null, 'ноль минут');
  eq(parse('couexa 0').error != null, true, 'и это сказано вслух');
});

t('голых минут больше 48 часов не принимаем', () => {
  eq(hm('couexa 3000'), 'ошибка', '3000 минут = 50 часов');
  eq(hm('couexa 2880'), '48:00', 'ровно 48 часов ещё можно');
});

t('ошибка не съедает запрос — список зон продолжает искаться', () => {
  const r = parse('couexa 5 70');
  eq(r.query, 'couexa', 'запрос');
  eq(r.sec, null, 'времени нет');
});

console.log('\n=== как это показывается игроку ===');

t('длительность словами', () => {
  eq(fmtDur(5 * 3600 + 36 * 60), '5 ч 36 мин', 'часы и минуты');
  eq(fmtDur(45 * 60), '45 мин', 'только минуты');
});

t('время закрытия по часам игрока', () => {
  const now = new Date(2026, 6, 26, 18, 30, 0).getTime();
  eq(fmtAt(5 * 3600 + 36 * 60, now), '00:06', 'переход через полночь');
  eq(fmtAt(45 * 60, now), '19:15', 'в тот же час');
});

console.log(`\n${fail ? 'ЕСТЬ ПРОВАЛЫ' : 'ВСЁ ЗЕЛЕНО'}: ${ok}/${ok + fail} проверок пройдено`);
process.exit(fail ? 1 : 0);
