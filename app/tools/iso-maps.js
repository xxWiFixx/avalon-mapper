// Карты зон мира — в игровую изометрию.
//
// ЗАЧЕМ. OpenRadar хранит зоны видом строго СВЕРХУ: квадрат 800x800. В игре же карта
// нарисована изометрией — тот же квадрат, повёрнутый на 45° и сплющенный по высоте.
// Квадрат в плашке выглядит чужеродно рядом с картами Авалона, которые сняты прямо из
// игры и уже ромбом. Здесь приводим одно к другому: на выходе та же геометрия, что у
// assets/avalon-maps-crop, — 512x356, ромб вписан в прозрачный прямоугольник.
//
// ОТВЕТ: ЗЕРКАЛО + 225°. Подтверждено владельцем по скриншотам из игры (Лимхёрст,
// Мартлок, Тетфорд), это и есть умолчание. Ниже — как искали, чтобы не искать заново.
//
// Вариантов восемь, а не четыре: к четырём поворотам добавляется отражение. Про него
// сначала забыли, и все четыре чистых поворота оказались мимо — что закономерно,
// отражение поворотом не исправляется, сколько ни крути.
//
// Числами угол не берётся. У 199 зон Авалона карта есть в ОБОИХ источниках, причём наша
// снята прямо из игры, то есть эталон; совпадение дорожной сетки (Жаккар по 14 зонам)
// дало 45°=0.109 и 225°=0.116 против 135°=0.083 и 315°=0.072. Разброс тут копеечный —
// это шум, а не разделение, и попытка отбросить по нему два варианта была ошибкой.
//
// Что сработало: одна опора, которую ни с чем не спутать, — серый круг с синим знаменем
// и порталом у города. На игровом скриншоте он слева-сверху от площади (10:30 по
// циферблату). Четыре чистых поворота ставят его на 9:00, 13:30, 16:00 и 19:30 — мимо
// все; в зеркальном наборе на 10:30 встаёт ровно один.
//
// Запуск:  node tools/iso-maps.js [угол] [--mirror]     по умолчанию 225 с зеркалом
'use strict';
const fs = require('fs');
const path = require('path');
const sharp = require('../node_modules/sharp');

const SRC = path.join(__dirname, '..', 'assets', 'world-maps');
const OUT = path.join(__dirname, '..', 'assets', 'world-maps-iso');
const ISO_RATIO = 1.44;                        // пропорция ромба в игре (замерена, см. crop-maps.js)
const OUT_W = 512;
const OUT_H = Math.round(OUT_W / ISO_RATIO);
// Умолчание — проверенный вариант. Запустить инструмент без аргументов и молча получить
// неверно развёрнутые карты нельзя: это ровно та ошибка, которую здесь уже допустили.
const DEG = Number(process.argv[2]) || 225;
const MIRROR = !process.argv.includes('--no-mirror');

if (![45, 135, 225, 315].includes(DEG)) {
  console.error('Угол должен быть 45, 135, 225 или 315 — иначе ромба не выйдет.');
  process.exit(1);
}
if (!fs.existsSync(SRC)) {
  console.error('Нет папки ' + SRC + ' — сначала node tools/fetch-world-maps.js');
  process.exit(1);
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const files = fs.readdirSync(SRC).filter(n => /^\d{4}\.webp$/.test(n));
  console.log('карт:', files.length, '| поворот:', DEG + '°',
    '| зеркало:', MIRROR ? 'да' : 'нет', '| на выходе', OUT_W + 'x' + OUT_H);
  let done = 0, bad = 0;
  for (const n of files) {
    try {
      let img = sharp(path.join(SRC, n));
      // Зеркалим ДО поворота: отражение и поворот местами не переставляются, и порядок
      // здесь тот же, в каком варианты показывались владельцу на сверке.
      if (MIRROR) img = sharp(await img.flop().png().toBuffer());
      await img
        // Поворот вокруг центра с прозрачным фоном: квадрат становится ромбом, а рамка
        // вырастает до диагонали. Дальше сплющиваем её в игровую пропорцию — ромб
        // ложится ровно в прямоугольник, без полей и без обрезки углов.
        .rotate(DEG, { background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .resize(OUT_W, OUT_H, { fit: 'fill' })
        .webp({ quality: 82 })
        .toFile(path.join(OUT, n));
      done++;
      if (done % 100 === 0) console.log('  ' + done + '…');
    } catch (err) { bad++; console.warn('  не вышло', n + ':', err.message); }
  }
  const size = fs.readdirSync(OUT).filter(x => /\.webp$/.test(x))
    .reduce((s, x) => s + fs.statSync(path.join(OUT, x)).size, 0);
  console.log('\nготово: ' + done + ', ошибок ' + bad + ', итого ' + (size / 1048576).toFixed(1) + ' МБ');
  fs.writeFileSync(path.join(OUT, 'УГОЛ.txt'),
    'Повёрнуто на ' + DEG + '°' + (MIRROR ? ' с зеркалом' : '')
    + ' из assets/world-maps инструментом tools/iso-maps.js.\n'
    + 'Проверено владельцем по скриншотам из игры. Перебрать иначе, если когда-нибудь\n'
    + 'понадобится: node tools/iso-maps.js 45 --no-mirror\n');
})();
