// Жив ли слушатель трафика — и когда его пора переоткрывать.
//
// ЗАЧЕМ. Сырой сокет умеет замолкать НАВСЕГДА и молча: спящий компьютер, смена адаптера
// (Wi-Fi ↔ кабель, VPN), сброшенный интерфейс. Сокет при этом остаётся «открытым», recv
// исправно отвечает «пусто», ошибок нет — просто пакеты больше не приходят никогда.
// У игрока это выглядело так: приложение час считало его в одной зоне, и вернул её к
// жизни только ПЕРЕЗАПУСК. Разовый пропуск перехода так себя не ведёт — он чинится сам
// на следующем переходе; чинит только перезапуск ровно то, что умерло насовсем.
//
// ПОЧЕМУ «МОЛЧАНИЕ» — НАДЁЖНЫЙ ПРИЗНАК. Photon болтает непрерывно: движение, пинги,
// состояние мира — десятки пакетов в секунду, даже когда игрок стоит на месте. Минута
// полной тишины при ЗАПУЩЕННОЙ игре не бывает нормой: значит слушаем в пустоту.
//
// ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ. Она не смотрит на зоны и переходы вовсе. Отсутствие
// ПЕРЕХОДОВ — это норма (игрок может фармить одну зону часами), а отсутствие ПАКЕТОВ —
// нет. Путать эти два молчания нельзя: на первом мы бы дёргали сокет у спокойно
// играющего человека.
'use strict';

// Сколько тишины считать смертью. Минута с лишним: достаточно длинно, чтобы не спутать
// с загрузкой зоны или свёрнутой на минуту игрой, и достаточно коротко, чтобы игрок не
// успел уйти далеко с залипшей зоной.
const SILENCE_MS = 90000;

// packets — сколько пакетов Photon поймано ВСЕГО с запуска слушателя (счётчик только растёт);
// gameRunning — запущена ли игра (без неё тишина законна и ничего не значит).
// → 'ok' | 'revive'
function createHealth({ silenceMs = SILENCE_MS } = {}) {
  let seen = -1;           // сколько пакетов было на прошлой проверке
  // Именно null, а не 0: «ещё не засекали» и «засекли в нулевую миллисекунду» — разные
  // вещи, и через ложность их не различить. С нулём проверка «первого тика» срабатывала
  // на каждом тике подряд, часы не накапливались, и сторож не воскресил бы сокет никогда.
  let changedAt = null;    // когда счётчик последний раз двигался
  return {
    tick({ packets = 0, gameRunning = false, now = Date.now() } = {}) {
      // Игры нет — тишина ожидаема. Часы сдвигаем, иначе после долгого перерыва
      // (игрок закрыл игру на ночь) первый же тик объявил бы сокет мёртвым.
      if (!gameRunning) { seen = packets; changedAt = now; return 'ok'; }
      if (packets !== seen) { seen = packets; changedAt = now; return 'ok'; }
      if (changedAt === null) { changedAt = now; return 'ok'; }   // первый тик при живой игре
      if (now - changedAt < silenceMs) return 'ok';
      // Признали мёртвым. Часы сдвигаем сразу: сокет сейчас переоткроют, и следующий
      // приговор должен выноситься по НОВОЙ тишине, а не по этой же.
      changedAt = now;
      seen = packets;
      return 'revive';
    },
    // Слушатель переоткрыли — счёт тишины начинается заново.
    reset(now = Date.now()) { seen = -1; changedAt = now; },
    // Для строки состояния: сколько уже длится тишина (null — счёт не начат).
    silentFor(now = Date.now()) { return changedAt === null ? null : now - changedAt; },
  };
}

module.exports = { createHealth, SILENCE_MS };
