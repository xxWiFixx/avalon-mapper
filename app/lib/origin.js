// К какой зоне привязать найденный портал.
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНО. Раньше правило было одно и молчаливое: «портал ведёт ИЗ той зоны,
// которая сейчас записана как текущая». Пока плашка зоны читается — всё честно. А стоит
// ей один раз не прочитаться (переход между зонами, экран загрузки, плашку заслонило),
// как текущей остаётся ПРЕДЫДУЩАЯ зона, и портал молча уезжает не туда: игрок прошёл
// A → B, проверил в B портал в C, а на карте появилось ребро A ⇄ C, и портала A ⇄ B
// не существует вовсе. Хуже всего, что об ошибке никто не узнаёт — она выглядит как
// нормальная запись.
//
// Новое правило: если мы не уверены, ОТКУДА портал, — не выдумываем, а откладываем.
// Портал ждёт в стороне, пока плашка не прочитается (обычно 1–3 секунды), и только
// потом ложится в карту. Не дождались — говорим вслух, а не пишем наугад.
'use strict';

// Сколько зона остаётся надёжной без нового подтверждения. Фоновый опрос подтверждает
// её каждые 1,5–6 с, так что 20 с — это три пропущенных опроса подряд: игрок уже мог
// уйти через портал, и верить старой записи больше нельзя.
const FRESH_MS = 20000;
// Сколько отложенный портал ждёт свою зону. Дольше держать опасно: за полминуты игрок
// успевает уйти в другую зону, и портал привязался бы к ней.
const PARK_TTL_MS = 25000;
const PARK_MAX = 4;

// zoneNow    — что прочиталось на кадре этого же нажатия (null, если не прочиталось);
// zoneTried  — плашку на этом кадре СНИМАЛИ (то есть zoneNow=null означает «не прочиталась»,
//              а не «не смотрели»);
// currentZone/seenAt — последняя известная зона и когда её подтвердили;
// watching   — включено ли слежение за плашкой (если нет, зону задаёт человек руками).
// → { origin, park, why }
function decide({ zoneNow = null, zoneTried = false, currentZone = null, seenAt = 0, now = Date.now(), watching = true } = {}) {
  if (zoneNow) return { origin: zoneNow, park: false, why: 'плашка прочитана на этом же кадре' };
  // Слежение выключено — плашку никто не читает и уже не прочитает. Значит откладывать
  // НЕЛЬЗЯ: отложенное разбирается только из опроса, а опроса нет, и портал молча
  // простоял бы до вытеснения. Либо зону задали руками — верим ей, другого источника
  // нет; либо не задали — и тогда честный ответ «спроси», а не «подожди».
  // Проверка стоит РАНЬШЕ !currentZone именно поэтому.
  if (!watching) {
    return currentZone
      ? { origin: currentZone, park: false, why: 'слежение выключено, зона задана вручную' }
      : { origin: null, park: false, ask: true, why: 'слежение выключено, а зона ещё не задана' };
  }
  if (!currentZone) return { origin: null, park: true, why: 'зона ещё ни разу не распознана' };
  // Плашку сняли ВМЕСТЕ с этим тултипом — и не прочитали. Раз тултип на экране есть,
  // игра отрисована и плашка на месте: значит промахнулся OCR, зоны нет в списке или
  // область настроена мимо. Ни одна из причин не подтверждает, что мы всё ещё там,
  // где помним, — а помним мы старую зону ещё пару секунд после входа в новую: фоновый
  // опрос меняет её только со второго одинакового чтения. Нажатие в этот зазор плюс
  // промах по плашке — единственное оставшееся место, где в карту молча уезжало ребро
  // из НЕ ТОЙ зоны. Поэтому не гадаем по памяти, а откладываем: в обычной игре условие
  // почти не наступает (на загрузке зоны порталов не видно, тултипу взяться неоткуда),
  // а когда наступает — память как раз и подводит.
  if (zoneTried) return { origin: null, park: true, why: 'плашку сняли вместе с тултипом и не прочитали' };
  const age = now - (seenAt || 0);
  if (age <= FRESH_MS) return { origin: currentZone, park: false, why: `зона подтверждена ${Math.round(age / 1000)} с назад` };
  return { origin: null, park: true, why: `зону не подтверждали ${Math.round(age / 1000)} с — мог уйти через портал` };
}

// ЗДЕСЬ БЫЛО allowPassive — правило «считать ли смену зоны порталом».
//
// Убрано вместе с самими пассивными рёбрами. Причина стоит того, чтобы её знать, иначе
// идея вернётся: вывод «игрок был в A, теперь в B, значит между ними проход» верен, только
// если ни одной зоны между ними мы не пропустили. А пропустить их проще простого — опрос
// плашки прекращается, когда игра не запущена, пропускается на экране загрузки и при
// свёрнутом окне. Любой такой перерыв склеивал зону ДО него с зоной ПОСЛЕ, и в карту
// уезжал портал между чем угодно. Заплатки (нет городов, свежесть зоны) закрывали
// отдельные случаи, но не сам способ рассуждения. Портал попадает в карту, только если
// прочитан его тултип.

// Отложенные порталы: те, для которых зона на момент нажатия была неизвестна.
// Живут секунды, поэтому ни на диск, ни в сеть не попадают — только в памяти.
function createParking({ ttlMs = PARK_TTL_MS, max = PARK_MAX } = {}) {
  let items = [];
  return {
    // → { size, dropped }: сколько порталов ждёт и кого вытеснили.
    // Вытесненного обязательно возвращаем наружу: раньше он исчезал молча, а игроку уже
    // пообещали «запишу, как только пойму». Молчаливая потеря после обещания — худший
    // вид потери: игрок не переснимет портал, потому что уверен, что тот записан.
    park(tip, at = Date.now()) {
      items.push({ tip, at });
      const over = items.length - max;
      const dropped = over > 0 ? items.splice(0, over).map(it => it.tip) : [];
      return { size: items.length, dropped };
    },
    // Зона наконец известна — забираем всё, что ещё не протухло.
    // → { ready: [tip], lost: [tip] }
    take(now = Date.now()) {
      const ready = [], lost = [];
      for (const it of items) (now - it.at <= ttlMs ? ready : lost).push(it.tip);
      items = [];
      return { ready, lost };
    },
    // Протухшие выбрасываем и без прихода зоны: иначе они дождались бы следующей,
    // уже неверной, и молча легли бы не туда.
    expire(now = Date.now()) {
      const lost = items.filter(it => now - it.at > ttlMs).map(it => it.tip);
      if (lost.length) items = items.filter(it => now - it.at <= ttlMs);
      return lost;
    },
    size() { return items.length; },
  };
}

module.exports = { decide, createParking, FRESH_MS, PARK_TTL_MS, PARK_MAX };
