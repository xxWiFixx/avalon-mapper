// Определение зоны игрока по трафику игры.
//
// ЗАЧЕМ. Сейчас зона читается с экрана: раз в 1,5 с снимается полоска под миникартой
// и распознаётся. Работает, но стоит снимка и ошибается на нечитаемой плашке. При смене
// локации клиент получает от сервера операцию opChangeCluster, и в ней лежит id кластера —
// это тот же факт, но без экрана вовсе.
//
// ЧТО ИМЕННО ИЩЕМ. Разбирать Photon целиком не нужно: id лежит в пакете обычной строкой.
//   Дороги Авалона — «TNL-235»
//   зоны мира      — «4208» (четыре цифры)
// Оба вида сопоставляются с именем по data-static/cluster-ids.json (854 зоны, собирается
// tools/build-cluster-ids.js из того же дампа игры, что и остальные справочники).
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ИСКАТЬ ПОДСТРОКУ. Тот же «TNL-235» встречается и в других
// операциях — например, opSubscribeToCluster присылает СПИСОК соседних кластеров
// (в замере игрока их было семнадцать). Взять оттуда — значит объявить игрока стоящим
// в зоне, мимо которой он только проходил. Поэтому id принимается, лишь когда в пакете
// ровно один кандидат: список соседей отсеивается сам собой.
const IDS = require('../data-static/cluster-ids.json');

// Строки в потоке лежат как есть, но вокруг них двоичный мусор, поэтому границы слова
// задаём явно: id не должен продолжаться цифрой или буквой.
const TNL = /TNL-\d{3}/g;
const NUM = /(?<![\dA-Za-z])\d{4}(?![\dA-Za-z])/g;

// Все кандидаты в буфере, без решения. Отдельно от pickCluster, чтобы это можно
// было прогнать по записи и посмотреть, что вообще ловится.
function findCandidates(buf) {
  const s = Buffer.isBuffer(buf) ? buf.toString('latin1') : String(buf);
  const out = [];
  for (const m of s.matchAll(TNL)) if (IDS[m[0]]) out.push(m[0]);
  for (const m of s.matchAll(NUM)) if (IDS[m[0]]) out.push(m[0]);
  return out;
}

// Зона из одного пакета: имя или null. Неоднозначный пакет — это НЕ смена зоны,
// и молчание здесь честнее догадки: ошибка в зоне уводит портал не туда, а такие
// записи выглядят как настоящие (см. lib/origin.js — там та же беда лечилась).
function pickCluster(buf) {
  const c = findCandidates(buf);
  if (c.length !== 1) return null;
  const id = c[0];
  return { id, zone: IDS[id], avalon: id.startsWith('TNL-') };
}

module.exports = { pickCluster, findCandidates, IDS };
