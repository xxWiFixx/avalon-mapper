// Определение зоны игрока по трафику игры.
//
// ЗАЧЕМ. Сейчас зона читается с экрана: раз в 1,5 с снимается полоска под миникартой
// и распознаётся. Работает, но стоит снимка и ошибается на нечитаемой плашке. При смене
// локации клиент получает от сервера ответ на операцию opChangeCluster, и в нём лежит
// id кластера — это тот же факт, но без экрана вовсе.
//
// ЧТО ИМЕННО ИЩЕМ. Ответ на операцию 41 (opChangeCluster). Id кластера — параметр 0:
//   Дороги Авалона — «TNL-235»
//   зоны мира      — «4208» (четыре цифры)
// Имя берётся из data-static/cluster-ids.json (854 зоны, собирается tools/build-cluster-ids.js
// из того же дампа игры, что и остальные справочники).
//
// ПОЧЕМУ НЕЛЬЗЯ ИСКАТЬ ПОДСТРОКУ. Так и было сделано сначала, и это оказалось неверно.
// Тот же «TNL-235» лежит в куче других сообщений: opGetClusterMapInfo (игрок открыл
// карту), opSubscribeToCluster (список соседних кластеров), opClientPerformanceStats
// (телеметрия раз в несколько секунд), opJoin. На записи настоящей игры поиск строки
// дал 497 срабатываний по 167 зонам — при тринадцати настоящих переходах. Игрок видел
// это как «зоны дублируются» и «при открытии аукциона посыпались локации».
// Отсеять их по содержимому невозможно: в пакете лежит ровно один id, ничем не
// отличающийся от настоящего. Поэтому смотрим не на строку, а на операцию (lib/photon.js).
const IDS = require('../data-static/cluster-ids.json');
const photon = require('./photon');

const OP_CHANGE_CLUSTER = 41;
const P_CLUSTER_ID = 0;

// Зона из одного UDP-пакета: { id, zone, avalon } или null.
// Молчание здесь честнее догадки: ошибка в зоне уводит портал не туда, а такие записи
// выглядят как настоящие (см. lib/origin.js — там та же беда лечилась).
function pickCluster(buf) {
  for (const m of photon.responses(buf)) {
    if (m.code !== OP_CHANGE_CLUSTER) continue;
    const id = m.params[P_CLUSTER_ID];
    // hasOwn, а не просто IDS[id]: id приходит из пакета, то есть снаружи. На «__proto__»
    // и «constructor» обычный поиск вернул бы унаследованное свойство — правдоподобное
    // на вид, — и зоной стал бы объект вместо имени. Таблица — обычный JSON, своей
    // защиты у неё нет.
    if (typeof id !== 'string' || !Object.hasOwn(IDS, id)) continue;
    return { id, zone: IDS[id], avalon: id.startsWith('TNL-') };
  }
  return null;
}

module.exports = { pickCluster, IDS };
