// Настройки безопасности окон — в одном месте и с одной сборкой.
//
// История этого файла стоит того, чтобы её знать. Сначала настройки лежали прямо
// в main.js замороженным образцом, а к нему дописывался preload через
// `Object.assign(SAFE_WEB, { preload })`. Это ошибка: Object.assign пишет в ЦЕЛЬ,
// а цель заморожена — вызов бросает TypeError, и приложение переставало открываться
// вовсе. Проверки этого не поймали, потому что ни один тест не создаёт окон.
// Отсюда два правила, закреплённых здесь и в win-prefs.test.js:
//   1. цель сборки — всегда новый объект;
//   2. безопасные свойства применяются ПОСЛЕДНИМИ, поэтому их нельзя случайно
//      ослабить, передав то же имя в extra.
'use strict';

// Все четыре и так стоят по умолчанию в Electron 38, но выписаны намеренно: код
// открытый, и читателю не должно приходиться помнить умолчания версии, чтобы
// убедиться, что в окнах нет Node, нет доступа к нашему контексту и есть песочница.
const SAFE_WEB = Object.freeze({
  contextIsolation: true,   // рендерер не видит наш контекст
  nodeIntegration: false,   // никакого require в странице
  sandbox: true,            // процесс страницы в песочнице ОС
  webSecurity: true,        // те же правила источников, что в браузере
});

// preload — путь к мосту этого окна (у каждого окна свой, минимальный).
// extra — прочие настройки окна; ослабить безопасные они не могут.
function webPrefs(preload, extra) {
  return Object.assign({}, extra || {}, SAFE_WEB, { preload });
}

module.exports = { SAFE_WEB, webPrefs };
